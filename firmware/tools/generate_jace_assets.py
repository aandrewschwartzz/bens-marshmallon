#!/usr/bin/env python3
"""Render the original Jace SVG sprites to LVGL ARGB8888 assets.

Requires Pillow and either rsvg-convert or CairoSVG.
"""
from pathlib import Path
import shutil
import subprocess

from PIL import Image

from generate_marshmallon_assets import format_bytes

ROOT = Path(__file__).resolve().parents[1]
ASSETS = (("jace_home", 104, 114), ("jace_win", 94, 126), ("jace_lose", 94, 126))


def main():
    preview_dir = ROOT / "assets/generated"
    preview_dir.mkdir(exist_ok=True)
    header = ['#pragma once', '', '#include "lvgl.h"', '']
    source = ['// Generated by tools/generate_jace_assets.py from original SVG artwork.',
              '#include "jace_assets.h"', '']
    for name, width, height in ASSETS:
        svg = ROOT / f"assets/{name}.svg"
        png = preview_dir / f"{name}.png"
        if shutil.which("rsvg-convert"):
            subprocess.run(['rsvg-convert', '-w', str(width), '-h', str(height),
                            '-o', str(png), str(svg)], check=True)
        else:
            import cairosvg
            cairosvg.svg2png(url=str(svg), write_to=str(png),
                            output_width=width, output_height=height)
        image = Image.open(png).convert('RGBA')
        assert image.size == (width, height)
        data = image.tobytes('raw', 'BGRA')
        header.append(f'LV_IMAGE_DECLARE({name});')
        source.extend([
            f'static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{',
            format_bytes(data), '};', '',
            f'const lv_image_dsc_t {name} = {{',
            '    .header = {', '        .magic = LV_IMAGE_HEADER_MAGIC,',
            '        .cf = LV_COLOR_FORMAT_ARGB8888,', '        .flags = 0,',
            f'        .w = {width},', f'        .h = {height},', f'        .stride = {width * 4},',
            '    },', f'    .data_size = sizeof({name}_map),', f'    .data = {name}_map,', '};', '',
        ])
    (ROOT / 'main/jace_assets.h').write_text('\n'.join(header) + '\n')
    (ROOT / 'main/jace_assets.c').write_text('\n'.join(source))


if __name__ == '__main__':
    main()
