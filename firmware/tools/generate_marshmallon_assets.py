#!/usr/bin/env python3
"""Render the prototype's canonical SVG art and emit LVGL ARGB8888 assets."""

from pathlib import Path
import subprocess

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "assets"
PNG_DIR = ASSET_DIR / "generated"
OUTPUT_C = ROOT / "main" / "marshmallon_assets.c"
OUTPUT_H = ROOT / "main" / "marshmallon_assets.h"

ASSETS = (
    ("marshmallon_home", 104, 114),
    ("marshmallon_win", 94, 126),
    ("marshmallon_lose", 94, 126),
)


def render_png(name: str, width: int, height: int) -> Path:
    PNG_DIR.mkdir(parents=True, exist_ok=True)
    source = ASSET_DIR / f"{name}.svg"
    output = PNG_DIR / f"{name}.png"
    subprocess.run(
        [
            "rsvg-convert",
            "--width",
            str(width),
            "--height",
            str(height),
            "--output",
            str(output),
            str(source),
        ],
        check=True,
    )
    return output


def bgra_bytes(path: Path, width: int, height: int) -> bytes:
    image = Image.open(path).convert("RGBA")
    if image.size != (width, height):
        raise ValueError(f"{path} rendered at {image.size}, expected {(width, height)}")
    pixels = bytearray()
    for red, green, blue, alpha in image.get_flattened_data():
        pixels.extend((blue, green, red, alpha))
    return bytes(pixels)


def format_bytes(data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in chunk) + ",")
    return "\n".join(lines)


def main() -> None:
    header = [
        "#pragma once",
        "",
        '#include "lvgl.h"',
        "",
    ]
    source = [
        "// Generated by tools/generate_marshmallon_assets.py from the canonical SVG artwork.",
        '#include "marshmallon_assets.h"',
        "",
    ]

    for name, width, height in ASSETS:
        png = render_png(name, width, height)
        data = bgra_bytes(png, width, height)
        header.append(f"LV_IMAGE_DECLARE({name});")
        source.extend(
            [
                f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{",
                format_bytes(data),
                "};",
                "",
                f"const lv_image_dsc_t {name} = {{",
                "    .header = {",
                "        .magic = LV_IMAGE_HEADER_MAGIC,",
                "        .cf = LV_COLOR_FORMAT_ARGB8888,",
                "        .flags = 0,",
                f"        .w = {width},",
                f"        .h = {height},",
                f"        .stride = {width * 4},",
                "    },",
                f"    .data_size = sizeof({name}_map),",
                f"    .data = {name}_map,",
                "};",
                "",
            ]
        )

    OUTPUT_H.write_text("\n".join(header) + "\n", encoding="utf-8")
    OUTPUT_C.write_text("\n".join(source), encoding="utf-8")


if __name__ == "__main__":
    main()
